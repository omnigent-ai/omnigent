import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { PALETTES, PALETTE_TOKEN_CSS_NAMES, themePalettes } from "../src/lib/themePalette.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(root, "src/themePalettes.generated.css");
// The server assigns project colors from the same palette ids.
const paletteIdsPath = resolve(root, "../omnigent/theme_palettes_generated.py");
const check = process.argv.slice(2).includes("--check");
const unexpectedArgs = process.argv.slice(2).filter((argument) => argument !== "--check");

if (unexpectedArgs.length > 0) {
  throw new Error(`Unknown arguments: ${unexpectedArgs.join(", ")}`);
}

function selectorFor(palette, mode) {
  if (palette.id === "omni") {
    return mode === "light" ? ":root:not(.dark):not([data-theme])" : ".dark:not([data-theme])";
  }
  return mode === "light"
    ? `:root:not(.dark)[data-theme="${palette.id}"]`
    : `.dark[data-theme="${palette.id}"]`;
}

function rule(selector, declarations) {
  return `${selector} {\n${declarations.map(([name, value]) => `  ${name}: ${value};`).join("\n")}\n}`;
}

function paletteRules(palette, mode) {
  const selector = selectorFor(palette, mode);
  const tokens = palette.tokens[mode];
  const declarations = Object.entries(PALETTE_TOKEN_CSS_NAMES).map(([key, cssName]) => [
    `--${cssName}`,
    tokens[key],
  ]);
  return [rule(selector, declarations)];
}

function customRules(mode) {
  const selector =
    mode === "light" ? ':root:not(.dark)[data-theme="custom"]' : '.dark[data-theme="custom"]';
  const declarations = Object.values(PALETTE_TOKEN_CSS_NAMES).map((cssName) => [
    `--${cssName}`,
    `var(--custom-${mode}-${cssName})`,
  ]);
  return [rule(selector, declarations)];
}

const rules = PALETTES.flatMap((palette) =>
  ["light", "dark"].flatMap((mode) => paletteRules(palette, mode)),
);
rules.push(...["light", "dark"].flatMap(customRules));

const source = `/* Generated by scripts/generate-theme-palettes.mjs. */\n\n${rules.join("\n\n")}\n`;
const formatted = await format(source, {
  ...(await resolveConfig(outputPath)),
  parser: "css",
});

const paletteIdsSource = `# Generated by web/scripts/generate-theme-palettes.mjs. Do not edit.
"""The web UI's theme palette ids, in the order Settings › Appearance lists them."""

THEME_PALETTE_IDS: tuple[str, ...] = (
${themePalettes.map((id) => `    "${id}",`).join("\n")}
)
`;

const outputs = [
  [outputPath, formatted, "Theme palette CSS"],
  [paletteIdsPath, paletteIdsSource, "Theme palette ids"],
];
await Promise.all(
  outputs.map(async ([path, content, label]) => {
    if (check) {
      const existing = await readFile(path, "utf8").catch(() => "");
      if (existing !== content) {
        console.error(`${label} is stale. Run \`just generate-theme-palettes\`.`);
        process.exitCode = 1;
      }
    } else {
      await writeFile(path, content);
      console.log(`Generated ${path}`);
    }
  }),
);
