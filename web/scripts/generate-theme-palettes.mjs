import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { DEFAULT_PALETTE, PALETTES, PALETTE_TOKEN_CSS_NAMES } from "../src/lib/themePalette.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
let outputRoot = root;
let check = false;
const args = process.argv.slice(2);
for (let index = 0; index < args.length; index++) {
  if (args[index] === "--check") {
    check = true;
  } else if (
    args[index] === "--output-root" &&
    args[index + 1] &&
    !args[index + 1].startsWith("--")
  ) {
    outputRoot = resolve(args[++index]);
  } else {
    throw new Error(`Unknown or incomplete argument: ${args[index]}`);
  }
}
const outputPath = resolve(outputRoot, "src/themePalettes.generated.css");

const backgroundKeys = new Set(["shellBackground", "sidebarBackground"]);
const androidRoles = {
  brand_background: "background",
  brand_foreground: "foreground",
  brand_muted_foreground: "mutedForeground",
  brand_border: "border",
  brand_primary: "primary",
  brand_on_primary: "primaryForeground",
  brand_secondary: "secondary",
  brand_on_secondary: "secondaryForeground",
  brand_accent: "brandAccent",
};

function androidColor(value, role) {
  if (/^#[0-9a-f]{6}$/i.test(value)) return value.toLowerCase();

  const component = "([+-]?(?:\\d+(?:\\.\\d*)?|\\.\\d+))";
  const match = value.match(
    new RegExp(`^oklch\\(\\s*${component}\\s+${component}\\s+${component}\\s*\\)$`, "i"),
  );
  if (!match) throw new Error(`Unsupported Android palette colour for ${role}: ${value}`);

  const lightness = Number(match[1]);
  const chroma = Number(match[2]);
  const hue = Number(match[3]) * (Math.PI / 180);
  const a = chroma * Math.cos(hue);
  const b = chroma * Math.sin(hue);
  const l = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (lightness - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const linearRgb = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  return `#${linearRgb
    .map((channel) => {
      const clamped = Math.max(0, Math.min(1, channel));
      const encoded = clamped <= 0.0031308 ? 12.92 * clamped : 1.055 * clamped ** (1 / 2.4) - 0.055;
      return Math.round(encoded * 255)
        .toString(16)
        .padStart(2, "0");
    })
    .join("")}`;
}

function androidResources(tokens) {
  const colors = Object.entries(androidRoles).map(
    ([role, token]) => `    <color name="${role}">${androidColor(tokens[token], role)}</color>`,
  );
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-theme-palettes.mjs; do not edit. -->\n<resources>\n${colors.join("\n")}\n</resources>\n`;
}

function selectorFor(palette, mode) {
  if (palette.id === "omni") {
    return mode === "light" ? ":root:not(.dark):not([data-theme])" : ".dark:not([data-theme])";
  }
  return mode === "light"
    ? `:root:not(.dark)[data-theme="${palette.id}"]`
    : `.dark[data-theme="${palette.id}"]`;
}

function rule(selector, declarations) {
  return `${selector} {\n${declarations.map(([name, value]) => `  ${name}: ${value};`).join("\n")}\n}`;
}

function paletteRules(palette, mode) {
  const selector = selectorFor(palette, mode);
  const tokens = palette.tokens[mode];
  const declarations = Object.entries(PALETTE_TOKEN_CSS_NAMES)
    .filter(([key]) => !backgroundKeys.has(key))
    .map(([key, cssName]) => [`--${cssName}`, tokens[key]]);

  return [
    rule(selector, declarations),
    rule(`${selector} .app-shell`, [["background", tokens.shellBackground]]),
    rule(`${selector} .conversations-sidebar`, [["background", tokens.sidebarBackground]]),
  ];
}

function customRules(mode) {
  const selector =
    mode === "light" ? ':root:not(.dark)[data-theme="custom"]' : '.dark[data-theme="custom"]';
  const declarations = Object.entries(PALETTE_TOKEN_CSS_NAMES)
    .filter(([key]) => !backgroundKeys.has(key))
    .map(([, cssName]) => [`--${cssName}`, `var(--custom-${mode}-${cssName})`]);

  return [
    rule(selector, declarations),
    rule(`${selector} .app-shell`, [["background", `var(--custom-${mode}-shell-background)`]]),
    rule(`${selector} .conversations-sidebar`, [
      ["background", `var(--custom-${mode}-sidebar-background)`],
    ]),
  ];
}

const rules = PALETTES.flatMap((palette) =>
  ["light", "dark"].flatMap((mode) => paletteRules(palette, mode)),
);
rules.push(...["light", "dark"].flatMap(customRules));

const source = `/* Generated by scripts/generate-theme-palettes.mjs. */\n\n${rules.join("\n\n")}\n`;
const formatted = await format(source, {
  ...(await resolveConfig(resolve(root, "src/themePalettes.generated.css"))),
  parser: "css",
});
const defaultPalette = PALETTES.find((palette) => palette.id === DEFAULT_PALETTE);
if (!defaultPalette) throw new Error(`Missing default theme palette: ${DEFAULT_PALETTE}`);
const outputs = new Map([
  [outputPath, formatted],
  [
    resolve(outputRoot, "android/app/src/main/res/values/colors_palette.xml"),
    androidResources(defaultPalette.tokens.light),
  ],
  [
    resolve(outputRoot, "android/app/src/main/res/values-night/colors_palette.xml"),
    androidResources(defaultPalette.tokens.dark),
  ],
]);

if (check) {
  const existingOutputs = await Promise.all(
    [...outputs.keys()].map((path) => readFile(path, "utf8").catch(() => "")),
  );
  [...outputs].forEach(([path, expected], index) => {
    if (existingOutputs[index] !== expected) {
      console.error(`${path} is stale. Run \`just generate-theme-palettes\`.`);
      process.exitCode = 1;
    }
  });
} else {
  await Promise.all([...outputs].map(([path, contents]) => writeFile(path, contents)));
  for (const path of outputs.keys()) {
    console.log(`Generated ${path}`);
  }
}
