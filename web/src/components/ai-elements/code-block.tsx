export const CodeBlockContent = ({
  code,
  language,
  showLineNumbers = false,
  wrap = false,
  className,
  leading,
  colorScheme,
}: {
  code: string;
  language: CodeLanguage;
  showLineNumbers?: boolean;
  /** Soft-wrap long lines instead of horizontal scrolling. */
  wrap?: boolean;
  /** Extra classes for the `<pre>`, e.g. to override its padding or background. */
  className?: string;
  /** Rendered before the code in the same box, e.g. a floated toolbar the first line wraps around. */
  leading?: ReactNode;
  /** Pin token colors to one scheme; by default they follow the app's. */
  colorScheme?: CodeColorScheme;
}) => {
  // Memoized raw tokens for immediate display
  // Raw ANSI escapes would flash on screen until the highlighter loads.
  const rawTokens = useMemo(
    () => createRawTokens(language === "ansi" ? stripAnsi(code) : code),
    [code, language],
  );

  // Synchronous cache lookup — avoids setState in effect for cached results
  const syncTokens = useMemo(
    () => highlightCode(code, language) ?? rawTokens,
    [code, language, rawTokens],
  );

  // Async highlighting result (populated after shiki loads)
  const [asyncTokens, setAsyncTokens] = useState<TokenizedCode | null>(null);
  const asyncKeyRef = useRef({ code, language });

  // Invalidate stale async tokens synchronously during render
  if (asyncKeyRef.current.code !== code || asyncKeyRef.current.language !== language) {
    asyncKeyRef.current = { code, language };
    setAsyncTokens(null);
  }

  useEffect(() => {
    let cancelled = false;

    highlightCode(code, language, (result) => {
      if (!cancelled) {
        setAsyncTokens(result);
      }
    });

    return () => {
      cancelled = true;
    };
  }, [code, language]);

  const tokenized = asyncTokens ?? syncTokens;

  return (
    <div
      className="relative overflow-auto"
      data-code-highlighted={tokenized === rawTokens ? "false" : "true"}
    >
      {leading}
      <CodeBlockBody
        className={cn(wrap && "whitespace-pre-wrap wrap-anywhere", className)}
        showLineNumbers={showLineNumbers}
        tokenized={tokenized}
        colorScheme={colorScheme}
      />
    </div>
  );
};

export const CodeBlock = ({
  code,
  language,
  showLineNumbers = false,
  wrap = false,
  className,
  children,
  ...props
}: CodeBlockProps) => {
  const contextValue = useMemo(() => ({ code }), [code]);

  return (
    <CodeBlockContext.Provider value={contextValue}>
      <CodeBlockContainer className={className} language={language} {...props}>
        {children}
        <CodeBlockContent
          code={code}
          language={language}
          showLineNumbers={showLineNumbers}
          wrap={wrap}
        />
      </CodeBlockContainer>
    </CodeBlockContext.Provider>
  );
};

export type CodeBlockCopyButtonProps = ComponentProps<typeof Button> & {
  onCopy?: () => void;
  onError?: (error: Error) => void;
  timeout?: number;
};

export const CodeBlockCopyButton = ({
  onCopy,
  onError,
  timeout = 2000,
  children,
  className,
  ...props
}: CodeBlockCopyButtonProps) => {
  const [isCopied, setIsCopied] = useState(false);
  const timeoutRef = useRef<number>(0);
  const { code } = useContext(CodeBlockContext);

  const copyToClipboard = useCallback(async () => {
    try {
      if (!isCopied) {
        await copyText(code);
        setIsCopied(true);
        onCopy?.();
        timeoutRef.current = window.setTimeout(() => setIsCopied(false), timeout);
      }
    } catch (error) {
      onError?.(error as Error);
    }
  }, [code, onCopy, onError, timeout, isCopied]);

  useEffect(
    () => () => {
      window.clearTimeout(timeoutRef.current);
    },
    [],
  );

  const Icon = isCopied ? CheckIcon : CopyIcon;

  return (
    <Button
      className={cn("shrink-0", className)}
      onClick={copyToClipboard}
      size="icon"
      variant="ghost"
      {...props}
    >
      {children ?? <Icon size={14} />}
    </Button>
  );
};

