"""Per-session Command Code wiring for the native harness.

Command Code reads its user config from ``~/.commandcode`` (resolved via
``HOME``/``USERPROFILE``); there is no config-home env var to relocate it. So
rather than mutating the user's ``settings.json`` (or the project's), the
Omnigent policy/approval bridge is injected as a **per-session Command Code
mod** passed with ``--mod <path>``. The mod is TypeScript, loaded by Command
Code's bundled jiti with no build step, and loaded ahead of user/project mods.

The mod reads its routing (server URL, auth headers, session id, the Omnigent
policy + permission endpoints) from ``hook_config.json`` written by the bridge,
and registers:

* ``beforeToolCall`` — POSTs a proto-style ``EvaluationRequest`` to the Omnigent
  policy endpoint and blocks (DENY) with the policy reason, otherwise defers to
  Command Code's own prompt (ALLOW);
* ``onPermissionRequest`` — answers Command Code's consent prompt from the web
  verdict, mirroring it into the Omnigent UI (Command Code has no
  ``PermissionRequest`` shell hook).
"""

from __future__ import annotations

import json
import os
from pathlib import Path

COMMANDCODE_HOME_ENV_VAR = "COMMANDCODE_HOME"
_BRIDGE_MOD_FILENAME = "omnigent-bridge.ts"

# NOTE: a plain (non-f-string) template. ``{config_path}`` is the only
# placeholder, substituted by ``.replace`` in ``write_commandcode_bridge_mod``.
# Keep every other brace single so the emitted file is valid TypeScript.
_BRIDGE_MOD_TEMPLATE = """\
// Generated by Omnigent for one commandcode-native session. Do not edit.
// Routes Command Code tool calls + permission prompts through the Omnigent
// policy engine. Loaded by `cmd --mod <this file>`.
import {readFileSync} from 'node:fs';

const CONFIG_PATH = {config_path};

export default function (cmd) {
  const env = (typeof process !== 'undefined' && process.env) ? process.env : {};
  let cfg = {};
  try {
    cfg = JSON.parse(readFileSync(CONFIG_PATH, 'utf8')) || {};
  } catch (err) {
    cfg = {};
  }
  // Prefer env-provided routing: the TUI may run inside an OS sandbox where
  // the bridge dir is not readable, but the terminal env is inherited.
  if (env.OMNIGENT_POLICY_EVALUATE_URL) cfg.policy_evaluate_url = env.OMNIGENT_POLICY_EVALUATE_URL;
  if (env.OMNIGENT_PERMISSION_URL) cfg.permission_url = env.OMNIGENT_PERMISSION_URL;
  if (env.OMNIGENT_HOOK_HEADERS) {
    try { cfg.headers = JSON.parse(env.OMNIGENT_HOOK_HEADERS); } catch (err) {}
  }
  if (!cfg.policy_evaluate_url) return;

  const headers = Object.assign({'Content-Type': 'application/json'}, cfg.headers || {});

  async function post(url, body) {
    try {
      const res = await fetch(url, {method: 'POST', headers, body: JSON.stringify(body)});
      if (!res.ok) return null;
      return await res.json();
    } catch (err) {
      return null;
    }
  }

  cmd.hooks({
    async beforeToolCall({toolName, input}) {
      if (typeof toolName === 'string' && toolName.startsWith('mcp__omnigent__')) {
        return undefined;  // already policy-checked by the Omnigent MCP relay
      }
      // POST /policies/evaluate expects the proto-style EvaluationRequest
      // envelope and answers {result: POLICY_ACTION_DENY|ASK|ALLOW, reason?}.
      // ASK is resolved server-side (the request long-polls), so it arrives as
      // a hard ALLOW/DENY; a stray ASK fails closed.
      const verdict = await post(cfg.policy_evaluate_url, {
        event: {
          type: 'PHASE_TOOL_CALL',
          target: '',
          data: {name: toolName, arguments: input || {}},
          context: {},
        },
      });
      const result = verdict && verdict.result;
      if (result === 'POLICY_ACTION_DENY' || result === 'POLICY_ACTION_ASK') {
        return {
          block: true,
          additionalContext: (verdict && verdict.reason) || 'Blocked by Omnigent policy.',
        };
      }
      return undefined;
    },
    async onPermissionRequest({toolName, input}) {
      // Claude-shaped PermissionRequest callback. The endpoint answers
      // hookSpecificOutput.decision.behavior = 'allow' | 'deny' (or an empty
      // body on timeout). A non-2xx (e.g. harness-mismatch 409) degrades to
      // undefined so Command Code's own prompt still runs.
      const verdict = await post(cfg.permission_url, {
        tool_name: toolName,
        tool_input: input || {},
      });
      const behavior =
        verdict && verdict.hookSpecificOutput && verdict.hookSpecificOutput.decision
          ? verdict.hookSpecificOutput.decision.behavior
          : undefined;
      if (behavior === 'allow') return 'allow';
      if (behavior === 'deny') return 'deny';
      return undefined;
    },
  });
}
"""


def resolve_user_commandcode_home(env: dict[str, str] | None = None) -> Path:
    """
    Resolve the Command Code user config home.

    :param env: Environment mapping to inspect. Defaults to ``os.environ``.
    :returns: ``$COMMANDCODE_HOME`` when set, else ``~/.commandcode``.
    """
    environ = os.environ if env is None else env
    override = environ.get(COMMANDCODE_HOME_ENV_VAR, "").strip()
    if override:
        return Path(override)
    home = environ.get("HOME") or environ.get("USERPROFILE") or ""
    return (Path(home) if home else Path.home()) / ".commandcode"


def write_commandcode_bridge_mod(bridge_dir: Path, dest: Path | None = None) -> Path:
    """
    Write the generated per-session Command Code mod.

    The mod embeds the absolute path of the bridge's ``hook_config.json`` as a
    fallback, but reads live routing from environment variables first (see
    :func:`build_commandcode_session_env`). Callers that run the TUI inside an
    OS sandbox should pass *dest* inside the workspace (a bind-mounted write
    root) so ``cmd --mod`` can read it.

    :param bridge_dir: Session bridge dir (should hold ``hook_config.json``).
    :param dest: Optional destination path (e.g. inside the workspace). Defaults
        to ``<bridge_dir>/omnigent-bridge.ts``.
    :returns: Path to the generated ``.ts`` mod (pass to ``cmd --mod``).
    """
    config_path = bridge_dir / "hook_config.json"
    mod_path = dest or (bridge_dir / _BRIDGE_MOD_FILENAME)
    mod_path.parent.mkdir(parents=True, exist_ok=True)
    mod_path.write_text(
        _BRIDGE_MOD_TEMPLATE.replace("{config_path}", json.dumps(str(config_path))),
        encoding="utf-8",
    )
    return mod_path


def build_commandcode_session_env(
    bridge_dir: Path,
    *,
    server_url: str | None = None,
    headers: dict[str, str] | None = None,
    session_id: str | None = None,
) -> dict[str, str]:
    """
    Build the env additions for the spawned Command Code TUI.

    Carries the Omnigent routing as **environment variables** (not only the
    ``hook_config.json`` file) because the TUI may run inside an OS sandbox
    where the bridge dir is not readable; the terminal env is inherited into
    the sandbox, so the generated mod can always reach the policy endpoints.

    :param bridge_dir: Session bridge dir.
    :param server_url: Omnigent server base URL (adds the two endpoint vars).
    :param headers: Auth headers to forward (serialized as JSON).
    :param session_id: Omnigent session id (used to build the endpoint URLs).
    :returns: Env additions for the terminal.
    """
    bridge_dir.mkdir(parents=True, exist_ok=True)
    env: dict[str, str] = {"COMMANDCODE_OMNIGENT_BRIDGE": str(bridge_dir)}
    if server_url and session_id:
        base = server_url.rstrip("/")
        env["OMNIGENT_POLICY_EVALUATE_URL"] = f"{base}/v1/sessions/{session_id}/policies/evaluate"
        env["OMNIGENT_PERMISSION_URL"] = (
            f"{base}/v1/sessions/{session_id}/hooks/permission-request"
        )
    if headers is not None:
        env["OMNIGENT_HOOK_HEADERS"] = json.dumps(headers)
    return env


