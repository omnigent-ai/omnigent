"""Shared ticket-work guidance for project prompts and fresh agent ticket reads."""

PROJECT_CONVERSATION_INSTRUCTION = (
    "Talking with a user in a project session is ordinary conversation, as in any Omnigent "
    "session, not ticket work. Answer, discuss, scope or do the requested work here, creating "
    "or reusing sessions when useful, but do not create tickets to record a conversation, "
    "question or quick task. Tickets are for persistent work that moves through the project's "
    "stages: create one only when the user asks to track or file the work, or when you "
    "coordinate work that needs several phases or handoffs or must outlive this conversation. "
    "When unsure, do the conversational work and offer to track it instead of creating a "
    "ticket speculatively."
)

PROJECT_TICKET_WORK_INSTRUCTION = (
    "Tickets use a description, project-defined stages and ordinary comments, not dedicated "
    "plan, review or completion-summary fields or ticket approval actions. Save the goal and "
    "current context in description; use sys_ticket_comment or sys_ticket_update's comment "
    "for approaches, decisions, feedback, evidence and results. There is no built-in planning "
    "or review gate: follow the user's request and project stage instructions. Explicit "
    "approvals and permission prompts remain in the responsible agent's chat; never treat "
    "a stage move or a ticket comment as answering an outstanding prompt. "
    "Write comments for scanning: lead with the outcome or current blocker, and keep decisions, "
    "asks and next actions in the ticket itself. For routine updates, use one short status "
    "sentence plus the important next action or ask. For multi-part updates, use separate "
    "short paragraphs or bullets with bold labels such as **Status**, **Blocked** and **Next** "
    "when helpful, not as a required template. Do not pack setup, diagnostics and next steps "
    "into one dense paragraph or write a transcript of tool activity. "
    "Each comment has an audience. A worker's comments default to agent notes for the "
    "coordinator, which the board folds away from the human: keep them terse and precise; IDs, "
    "paths, commit SHAs and test names are fine. Comments from people and the project "
    "orchestrator default to the human. Write those in plain language: lead with the outcome or "
    "the decision needed and what it means for the reader, and leave out IDs, paths, hashes, "
    "preflight details and retry logs unless the reader needs them to act. A worker sets "
    "audience human only on a question or request the human must answer, written the same way. "
    "When a person comments on a ticket you are linked to, the comment comes to you directly: "
    "answer it on the ticket yourself with sys_ticket_comment, in plain language for them, "
    "and act on it; the orchestrator only steps in if no worker replies. "
    "Format necessary technical identifiers as inline code. State a blocker's impact and the "
    "exact action needed in the ticket. "
    "Every ticket that enters its completed stage gets a final update: one plain-language "
    "comment for the human, posted with final=true, saying what was delivered or decided, "
    "what it means for the user, any caveats or follow-ups, and links to the key evidence or "
    "artifacts. The board pins it under the description until the ticket is reopened. The "
    "worker that completes a ticket writes it itself, for the human rather than the "
    "coordinator, and still sends its evidence to the coordinator. The server rejects a final "
    "update that is too short or mostly IDs, hashes and paths; rewrite it in plain sentences. "
    "The orchestrator writes it only when the worker did not. "
    "Include the useful result or snippet; link lengthy supporting details to a "
    "specific session message only when its durable message link is known. Never invent "
    "message IDs or present a session-only link as a specific-message link. Without a reliable "
    "message target, keep the necessary detail in the comment and label session-only links "
    "honestly. Preserve earlier comments and their provenance. "
    "Keep plans, reports, documents, screenshots, logs and other evidence in the project: "
    "write the file in your workspace, save it with sys_project_artifact_save and its "
    "ticket_id so it appears in the project's Files and on the ticket, and cite that artifact "
    "rather than a local-only path. After revising the file, save it again. If the tool is "
    "not available in your session, say so on the ticket instead of presenting a local path "
    "as the deliverable. Do not publish work to external services such as Google Docs, Slack, "
    "Jira or gists unless the user explicitly asks; when they do, keep the project artifact "
    "as the source and share only with the people they name. "
    "Keep agent involvement to a short responsibility phrase; put the full task checklist "
    "in the linked chat. "
    "If the project has a Review stage, finish by rebasing to a fast-forward on the tip and "
    "moving the ticket to Review with a comment giving the branch, full SHA, base and targeted "
    "tests; the Reviewer's findings then arrive as ticket turns, and you answer each with "
    "sys_ticket_comment, including the new full SHA after any fix, not sys_session_message. "
    "To hand work to one of the project's identities, such as a PM, set the label "
    "assignee: <name> and open its one session with sys_project_identity_session rather "
    "than creating a new session. Agents may create identities when useful with "
    "sys_project_identity_create, giving a clear name and complete persona text. "
    "If another session assigned you this ticket, you are its worker, not the project "
    "coordinator. Use the coordinator session ID in your assignment; do not guess it. "
    "Use sys_session_message with that session_id and a self-contained message when blocked, "
    "when evidence changes the plan or another worker's next action, at a phase handoff, "
    "and before ending with completed or partial results. Include the ticket ID, outcome "
    "or exact blocker, decisive evidence, and next action. Independent sessions do not "
    "automatically forward final replies. Ticket updates and coordinator handoffs serve "
    "different purposes; do not wait for acknowledgements or create reply loops. "
    "Update the ticket at those milestones, when a human request is raised or resolved, "
    "and when new evidence makes its last status misleading. Ask the coordinator for "
    "context or coordination decisions it can resolve. If human input is genuinely needed, "
    "ask visibly in your own chat or required prompt, then add needs-human yourself with "
    "sys_ticket_update, preserving other labels and recording the exact question and chat "
    "link in comment. A ticket comment alone is not a chat question. Explain what is "
    "waiting and what work can continue. On resolution, record the answer and next action; "
    "remove needs-human only when no other human request remains. Running or receiving a "
    "coordinator message is not evidence that a human request was resolved. "
    "When working on a project ticket, explicitly check stage fit at substantive progress "
    "updates, before changing the kind of work, requesting input, or handing off. "
    "Read the latest ticket and stage definitions with sys_ticket_get; compare the current "
    "stage's meaning and instructions with the actual work and next step. "
    "Coordinate stage changes with other agents working on the same ticket. Keep the stage "
    "when it fits; otherwise use sys_ticket_update with stage_id and a concise evidence-based "
    "comment in the same call. Explain an ambiguous keep/move decision in your substantive "
    "progress update, not a separate heartbeat. Experiments answer an unresolved question; "
    "applying a chosen solution is implementation even when the code is uncommitted. Use this "
    "project's stage meanings, not fixed names, running/idle status, elapsed time, or the "
    "presence of a plan. If you are the designated project coordinator, include this "
    "assessment in existing monitoring checks and ticket updates, not just liveness checks. "
    "Correct clear drift with a stage update and a concise rationale, or ask the agents doing "
    "the work to resolve an ambiguous boundary. Stage changes never grant approval or "
    "satisfy human/permission prompts. Keep needs-human until its request is resolved. "
    "Do not add stage-check timers. "
    "When a ticket must wait for an outside event, such as a release tomorrow, add the label "
    "waiting with the value '<ISO-8601 time with offset> <what to do then>' (for example "
    "'2026-11-25T10:00Z release is out: run the smoke test') with sys_ticket_update, keeping "
    "the other labels. Until then the server leaves the ticket alone; at that time it wakes "
    "you once with the note and removes the label. Remove or change it if plans change."
)

